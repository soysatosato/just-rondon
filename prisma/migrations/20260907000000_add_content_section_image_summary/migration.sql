-- 挿絵に説明文を持たせる。
--
-- ContentSection は image を前から持っていたが、描画側が出していなかったので
-- 挿絵は長らく画面に出ていなかった。出すようにしてすぐ足りないと分かったのが
-- 「この写真は何なのか」を書く場所である。コラムの挿絵は本文と一対一では
-- なく、本文が触れていない年代・場所・別個体を写していることが多い
-- (例: 赤い電話ボックスの回で、本文が語るのは K2 だが写真は現存する K1)。
-- 読者は写真だけを見て本文と食い違うと受け取る。
--
-- subtitle を流用しない。あれは見出しの直後に出るリード文で、画像より上に
-- 置かれる。画像の説明は画像の下に付かないとどの写真の話か分からない。
--
-- Wikimedia の写真は出典の明示が要る場面があり、その置き場も兼ねる。
-- null 可にするのは、挿絵そのものが任意で、説明の要らない写真もあるため。

ALTER TABLE "ContentSection" ADD COLUMN "imageSummary" TEXT;
