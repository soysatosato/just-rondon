/**
 * 「◯月のロンドン」の、年が替わっても使える本文。
 *
 * 年ごとに変わるもの(イベントの日付・祝日・日の出入り・週次ダイジェスト)は
 * ページがDBと計算から出す。ここに書くのは、来年も再来年もそのまま
 * 通用することだけ。「今年は〜」「2026年の〜」は書かないこと。
 *
 * 平年値の数字(最高16℃など)は本文にも書いてよい。平年値は10年に1度しか
 * 改訂されないが、改訂したら climate.ts と合わせて本文の数字も直すこと。
 *
 * マークダウンにはしない。太字が CommonMark の規則で崩れる問題
 * (CLAUDE.md)を避けるのと、ここは段落と箇条書きしか要らないため。
 */
export type MonthGuide = {
  month: number;
  /** h1 の下に出す2〜3文。その月を一言で言うと何か。 */
  lead: string;
  /**
   * トップの「今月のロンドン」に出す1〜2文。lead を縮めたもので、新しい事実は足さない。
   * トップは2行で切っていたため、lead が「東京の1…」のように数字の途中で切れていた。
   */
  teaser: string;
  /** meta description。全角120字以内。数字を入れて、他の月と書き分ける。 */
  description: string;
  /** 平年値の表の下に出す、数字の読み方。段落ごとに1要素。 */
  weather: string[];
  wear: {
    /** 「結局、何を着ればいいか」への一文の答え。 */
    summary: string;
    items: { label: string; body: string }[];
    /** 日本から持っていくと役に立つもの。 */
    pack: string[];
  };
  /** 旅程を組むときのコツ。混雑・時計の切り替え・休館など。 */
  tips: { title: string; body: string }[];
  /** 本文の内容に関係するサイト内のページ。 */
  links: { href: string; label: string }[];
};
