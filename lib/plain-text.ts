/**
 * マークダウンの文字列から記号を外し、1段落のプレーンテキストにする。
 *
 * カードの抜粋・記事のリード文・「早わかり」の値・JSON-LD など、
 * マークダウンとして描画しない場所に本文を出すときに通す。通さないと
 * `**強調**` や `[label](url)` が記号のまま読者に見える
 * (2026-10 の監査では /museums/national-gallery だけで ** が374個出ていた)。
 *
 * 強調は失われる。リード文でも太字を残したいなら、プレーンテキストに
 * せず MarkdownBody で描画すること。
 *
 * クライアントコンポーネントからも呼ぶので、このファイルには何も import しない。
 */
export function stripInlineMarkdown(md: string): string {
  return (
    md
      .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1") // [label](url) → label
      // 行頭の見出し・引用・箇条書き(作品解説には「- **アヌビス**…」の箇条書きがある)
      .replace(/^[ \t]*(?:(?:#{1,6}|>|[-*+]|\d+\.)[ \t]+|・)/gm, "")
      .replace(/\*\*([^*]+)\*\*/g, "$1") // **bold** → bold
      .replace(/(?<!\*)\*([^*]+)\*(?!\*)/g, "$1") // *italic* → italic
      .replace(/`([^`]+)`/g, "$1") // `code` → code
      // 対にならずに残った **(「グレードII*」の * に組を取られた場合など)
      .replace(/\*\*/g, "")
      .replace(/\s+/g, " ")
      // 段落をつないだ「。 次の文」の空白。和文の句読点・閉じ括弧の後には要らない
      .replace(/([。、！？」』）])\s/g, "$1")
      .trim()
  );
}
