const APPLY = process.argv.includes("--apply");
const ONLY = process.argv.find((a) => a.startsWith("--slug="))?.slice(7);

async function main() {
  const slugs = Object.keys(FLOWS).filter((s) => !ONLY || s === ONLY);
  if (ONLY && slugs.length === 0) {
    console.error(`slug=${ONLY} はこのスクリプトの対象外です`);
    process.exitCode = 1;
    return;
  }

  console.log(APPLY ? "== 投入 ==\n" : "== ドライラン(--apply で投入) ==\n");

  for (const slug of slugs) {
    const steps = FLOWS[slug];
    const spot = await prisma.attraction.findUnique({
      where: { slug },
      select: { id: true, name: true },
    });

    if (!spot) {
      console.error(`✗ ${slug} が見つかりません。先に add-attractions-2026-09.ts を流すこと`);
      process.exitCode = 1;
      continue;
    }

    console.log(`${spot.name} (${slug})  ${steps.length}ステップ`);
    steps.forEach((s) => console.log(`    ${s.kind.padEnd(9)} ${s.title}  ${s.body.length}字`));

    if (!APPLY) {
      console.log("");
      continue;
    }

    await prisma.$transaction([
      prisma.attractionVisitStep.deleteMany({ where: { attractionId: spot.id } }),
      prisma.attractionVisitStep.createMany({
        data: steps.map((s, i) => ({
          attractionId: spot.id,
          kind: s.kind,
          title: s.title,
          body: s.body,
          displayOrder: i + 1,
        })),
      }),
    ]);
    console.log("    → 投入\n");
  }

  const total = slugs.reduce((n, s) => n + FLOWS[s].length, 0);
  console.log(`対象 ${slugs.length}件 / 合計 ${total}ステップ`);
  if (!APPLY) console.log("\n--apply を付けると投入します。");
}

if (process.argv[1]?.includes("seed-visit-flow-2026-09")) {
  main()
    .catch((e) => {
      console.error(e);
      process.exitCode = 1;
    })
    .finally(() => prisma.$disconnect());
}
