async function main() {
  const bySlug = new Map<string, string>();
  for (const slug of new Set(rewrites.map((r) => r.slug))) {
    const museum = await db.museum.findUnique({
      where: { slug },
      select: { id: true },
    });
    if (!museum) throw new Error(`館が見つかりません: ${slug}`);
    bySlug.set(slug, museum.id);
  }

  for (const r of rewrites) {
    const current = await db.artwork.findUnique({
      where: { id: r.id },
      select: { title: true, museumId: true },
    });
    if (!current) throw new Error(`作品が見つかりません: ${r.id} (${r.title})`);
    if (current.museumId !== bySlug.get(r.slug))
      throw new Error(
        `館が一致しません: ${r.id} (${current.title}) 期待=${r.slug}`,
      );
    if (current.title !== r.title)
      throw new Error(
        `タイトル不一致: ${r.id} DB="${current.title}" 期待="${r.title}"`,
      );

    await db.artwork.update({
      where: { id: r.id },
      data: { description: r.description, highlights: r.highlights },
    });
    console.log(`更新: [${r.slug}] ${r.title}`);
  }
  console.log(`\n合計 ${rewrites.length} 件を更新しました。`);
}

