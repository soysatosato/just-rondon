async function main() {
  let count = 0;

  for (const r of RECOMMENDATIONS) {
    const souvenir = await db.souvenir.findUnique({
      where: { slug: r.slug },
      select: { id: true, name: true },
    });

    if (!souvenir) {
      console.warn(`× 見つからない: ${r.slug}`);
      continue;
    }

    await db.souvenir.update({
      where: { id: souvenir.id },
      data: { recommendation: r.recommendation },
    });

    count += 1;
    console.log(`✓ ${souvenir.name}`);
  }

  console.log(`\n${count}件に「どれを買うか」を追加。`);
}

const invokedDirectly = process.argv[1]?.endsWith(
  "seed-souvenir-recommendations.ts",
);

if (invokedDirectly) {
  main()
    .catch((err) => {
      console.error(err);
      process.exit(1);
    })
    .finally(async () => {
      await db.$disconnect();
    });
}
