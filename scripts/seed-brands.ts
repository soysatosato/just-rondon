async function main() {
  let order = 0;
  let heroResolved = 0;
  let figureResolved = 0;
  let itemImageResolved = 0;

  for (const b of BRANDS) {
    let heroColumns: ReturnType<typeof imageColumns>;
    if (b.heroUrl) {
      heroColumns = {
        image: b.heroUrl,
        imageSource: null,
        imageCredit: null,
        imageLink: null,
      };
      heroResolved += 1;
    } else {
      let hero: CommonsImage | null = null;
      if (b.commonsFile) {
        hero = await resolveCommonsImage(b.commonsFile);
        if (hero) heroResolved += 1;
      }
      heroColumns = imageColumns(hero);
    }

    const data = {
      name: b.name,
      engName: b.engName,
      category: b.category,
      blurb: b.blurb,
      appeal: b.appeal,
      story: b.story,
      buying: b.buying,
      founded: b.founded ?? null,
      origin: b.origin ?? null,
      royalWarrant: b.royalWarrant ?? false,
      priceRange: b.priceRange ?? null,
      website: b.website ?? null,
      tips: b.tips ?? null,
      instagramUrl: normaliseInstagramUrl(b.instagramUrl, b.slug),
      recommendLevel: b.recommendLevel,
      displayOrder: order++,
      ...heroColumns,
    };

    const brand = await db.brand.upsert({
      where: { slug: b.slug },
      create: { slug: b.slug, ...data },
      update: data,
    });

    // アイテムと図版は毎回入れ替える。displayOrder を保ったまま差分更新するより、
    // 消して入れ直すほうが seed の内容と DB が確実に一致する。
    await db.brandItem.deleteMany({ where: { brandId: brand.id } });
    if (b.items?.length) {
      // 画像の解決は1件ずつ待つ必要があるので、先にまとめて解決してから
      // createMany に渡す。解決できなかったものは画像なしで登録する
      // ——アイテム自体の説明は画像が無くても成立するため、
      // 図版(BrandImage)と違って行ごと捨てはしない。
      const items = await Promise.all(
        b.items.map(async (item) => ({
          item,
          image: item.commonsFile
            ? await resolveCommonsImage(item.commonsFile)
            : null,
        })),
      );

      for (const { item, image } of items) {
        if (item.commonsFile && !image) {
          console.log(`  ! 商品画像を解決できず: ${item.commonsFile}`);
        }
        if (image) itemImageResolved += 1;
      }

      await db.brandItem.createMany({
        data: items.map(({ item, image }, i) => ({
          brandId: brand.id,
          name: item.name,
          engName: item.engName ?? null,
          note: item.note,
          priceRange: item.priceRange ?? null,
          ...imageColumns(image),
          displayOrder: i,
        })),
      });
    }

    await db.brandStore.deleteMany({ where: { brandId: brand.id } });
    if (b.stores?.length) {
      await db.brandStore.createMany({
        data: b.stores.map((store, i) => ({
          brandId: brand.id,
          kind: store.kind,
          name: store.name,
          address: store.address ?? null,
          nearestStation: store.nearestStation ?? null,
          note: store.note ?? null,
          displayOrder: i,
        })),
      });
    }

    await db.brandFaq.deleteMany({ where: { brandId: brand.id } });
    if (b.faqs?.length) {
      await db.brandFaq.createMany({
        data: b.faqs.map((faq, i) => ({
          brandId: brand.id,
          question: faq.question,
          answer: faq.answer,
          displayOrder: i,
        })),
      });
    }

    await db.brandImage.deleteMany({ where: { brandId: brand.id } });
    if (b.images?.length) {
      for (const fig of b.images) {
        const afterBlock = fig.afterBlock ?? 0;
        const orientation = fig.orientation ?? "landscape";
        if ("url" in fig) {
          figureResolved += 1;
          await db.brandImage.create({
            data: {
              brandId: brand.id,
              section: fig.section,
              url: fig.url,
              caption: fig.caption,
              imageSource: null,
              imageCredit: null,
              imageLink: null,
              orientation,
              displayOrder: afterBlock,
            },
          });
          continue;
        }

        const image = await resolveCommonsImage(fig.commonsFile);
        // 解決できなかった図版は作らない。URL の無いレコードを残すと
        // 表示側で空の figure が出てしまう。
        if (!image) {
          console.log(`  ! 図版を解決できず: ${fig.commonsFile}`);
          continue;
        }
        figureResolved += 1;
        await db.brandImage.create({
          data: {
            brandId: brand.id,
            section: fig.section,
            url: image.url,
            caption: fig.caption,
            imageSource: "commons",
            imageCredit: image.credit,
            imageLink: image.link,
            orientation,
            displayOrder: afterBlock,
          },
        });
      }
    }

    console.log(`✓ ${b.name}${heroColumns.image ? "" : "（ヒーロー画像なし）"}`);
  }

  console.log(
    `\n${BRANDS.length}件を登録。ヒーロー画像 ${heroResolved}件、` +
      `本文中の図版 ${figureResolved}件、商品画像 ${itemImageResolved}件を解決。`,
  );
}

main()
  .catch((err) => {
    console.error(err);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
