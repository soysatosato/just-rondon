async function main() {
  let order = 0;
  let resolved = 0;

  for (const b of BRANDS) {
    let image: CommonsImage | null = null;
    if (b.commonsFile) {
      image = await resolveCommonsImage(b.commonsFile);
      if (image) resolved += 1;
    }

    const data = {
      name: b.name,
      engName: b.engName,
      category: b.category,
      blurb: b.blurb,
      story: b.story,
      buying: b.buying,
      founded: b.founded ?? null,
      origin: b.origin ?? null,
      royalWarrant: b.royalWarrant ?? false,
      priceRange: b.priceRange ?? null,
      buyAt: b.buyAt ?? [],
      flagship: b.flagship ?? null,
      website: b.website ?? null,
      tips: b.tips ?? null,
      recommendLevel: b.recommendLevel,
      displayOrder: order++,
      ...imageColumns(image),
    };

    const brand = await db.brand.upsert({
      where: { slug: b.slug },
      create: { slug: b.slug, ...data },
      update: data,
    });

    // アイテムは毎回入れ替える。displayOrder を保ったまま差分更新するより、
    // 消して入れ直すほうが seed の内容と DB が確実に一致する。
    await db.brandItem.deleteMany({ where: { brandId: brand.id } });
    if (b.items?.length) {
      await db.brandItem.createMany({
        data: b.items.map((item, i) => ({
          brandId: brand.id,
          name: item.name,
          engName: item.engName ?? null,
          note: item.note,
          priceRange: item.priceRange ?? null,
          displayOrder: i,
        })),
      });
    }

    console.log(`✓ ${b.name}${image ? "" : "（画像なし）"}`);
  }

  console.log(
    `\n${BRANDS.length}件を登録。画像を解決できたのは ${resolved}件。`,
  );
}

main()
  .catch((err) => {
    console.error(err);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
