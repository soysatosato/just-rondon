const APPLY = process.argv.includes("--apply");
const ONLY = process.argv.find((a) => a.startsWith("--slug="))?.slice(7);

async function main() {
  const slugs = Object.keys(FLOWS).filter((s) => !ONLY || s === ONLY);
  if (ONLY && slugs.length === 0) {
    console.error(`slug=${ONLY} はこのスクリプトの対象外です`);
    process.exitCode = 1;
    return;
  }

  // マークダウンが混ざっていたら投入前に止める。プレーンテキスト描画なので
  // ** やリンク記法を書くと記号がそのまま画面に出る。
  let broken = false;
  for (const slug of slugs) {
    for (const step of FLOWS[slug]) {
      const md = /\*\*|\[.+?\]\(.+?\)|^#|^- /m;
      if (md.test(step.body) || md.test(step.title)) {
        console.error(`✗ ${slug} / ${step.title}: マークダウン記法が入っています`);
        broken = true;
      }
    }
  }
  if (broken) {
    console.error("\nプレーンテキストに直してから流し直してください。");
    process.exitCode = 1;
    return;
  }

  console.log(APPLY ? "== 投入 ==\n" : "== ドライラン(--apply で投入) ==\n");

  let total = 0;
  for (const slug of slugs) {
    const attraction = await prisma.attraction.findUnique({
      where: { slug },
      include: { visitFlow: true, stories: true },
    });
    if (!attraction) {
      console.error(`✗ ${slug}: 見つかりません（先に add-attractions-2026-09-3.ts を流すこと）`);
      process.exitCode = 1;
      continue;
    }

    const steps = FLOWS[slug];
    total += steps.length;

    // 歩き方を入れると highlight 節が伏せられる。落ちる本文があれば警告する。
    const hidden = attraction.stories.filter((s) => s.kind === "highlight");
    const note = hidden.length > 0 ? `  ※highlight ${hidden.length}本が伏せられる` : "";

    console.log(`${attraction.name} (${slug})`);
    console.log(`  ${attraction.visitFlow.length}→${steps.length}ステップ${note}`);
    steps.forEach((s) => console.log(`    ${s.kind.padEnd(9)} ${s.title}`));

    if (APPLY) {
      await prisma.$transaction([
        prisma.attractionVisitStep.deleteMany({ where: { attractionId: attraction.id } }),
        prisma.attractionVisitStep.createMany({
          data: steps.map((s, i) => ({
            attractionId: attraction.id,
            kind: s.kind,
            title: s.title,
            body: s.body,
            displayOrder: i + 1,
          })),
        }),
      ]);
      console.log("    → 投入");
    }
    console.log("");
  }

  console.log(`対象 ${slugs.length}件 / ${total}ステップ`);
  if (!APPLY) console.log("\n--apply を付けると投入します。");
}

if (process.argv[1]?.includes("seed-visit-flow-2026-09-3")) {
  main()
    .catch((e) => {
      console.error(e);
      process.exitCode = 1;
    })
    .finally(() => prisma.$disconnect());
}
