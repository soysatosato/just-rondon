async function main() {
  const attraction = await db.attraction.findUnique({
    where: { slug: SLUG },
    select: { id: true, name: true, sections: { select: { id: true } } },
  });

  if (!attraction) {
    console.log(`SKIP ${SLUG} — 該当スポットなし`);
    return;
  }

  console.log(`=== ${attraction.name} — ${SECTIONS.length}セクション`);
  console.log(`既存セクション: ${attraction.sections.length}本`);
  SECTIONS.forEach((s, i) =>
    console.log(`  ${i + 1}. ${s.title} (${s.description.length}字)`),
  );

  if (!APPLY) {
    console.log("\n投入するには --apply を付けて再実行してください。");
    return;
  }

  // 作り直し。何度流しても同じ結果になるようにする。
  await db.attractionSection.deleteMany({
    where: { attractionId: attraction.id },
  });
  for (const [i, s] of SECTIONS.entries()) {
    await db.attractionSection.create({
      data: {
        attractionId: attraction.id,
        displayOrder: i + 1,
        title: s.title,
        description: s.description,
      },
    });
  }
  console.log("→ 投入しました");
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(async () => {
    await db.$disconnect();
  });
