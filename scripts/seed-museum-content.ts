async function main() {
  let hlTotal = 0;
  let tvTotal = 0;
  const missing: string[] = [];

  for (const seed of SEEDS) {
    const museum = await db.museum.findUnique({
      where: { slug: seed.slug },
      select: { id: true, name: true },
    });

    if (!museum) {
      missing.push(seed.slug);
      continue;
    }

    // 冪等にするため、この館の既存分を消してから入れ直す。
    await db.highlight.deleteMany({ where: { museumId: museum.id } });
    await db.trivia.deleteMany({ where: { museumId: museum.id } });

    await db.highlight.createMany({
      data: seed.highlights.map((h, i) => ({
        museumId: museum.id,
        title: h.title,
        location: h.location ?? null,
        body: h.body,
        order: i,
      })),
    });

    await db.trivia.createMany({
      data: seed.trivia.map((t) => ({
        museumId: museum.id,
        title: t.title,
        content: t.content,
      })),
    });

    hlTotal += seed.highlights.length;
    tvTotal += seed.trivia.length;
    console.log(
      `✓ ${museum.name} — 必見 ${seed.highlights.length}件 / 豆知識 ${seed.trivia.length}件`,
    );
  }

  console.log(
    `\n完了: ${SEEDS.length - missing.length}館に 必見${hlTotal}件 / 豆知識${tvTotal}件`,
  );
  if (missing.length > 0) {
    console.log("slug が見つからなかった:", missing.join(", "));
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => process.exit(0));
