const APPLY = process.argv.includes("--apply");
const SLUG_ARG = process.argv.find((a) => a.startsWith("--slug="));

async function main() {
  const slugs = SLUG_ARG
    ? [SLUG_ARG.split("=")[1]]
    : Object.keys(FLOWS);

  // マークダウンが混ざっていないか先に全部見る。
  // MuseumVisitFlow.tsx はプレーンテキストで描画するので、記号がそのまま出る。
  let broken = false;
  for (const slug of slugs) {
    if (!FLOWS[slug]) {
      console.error(`✗ ${slug}: FLOWS にありません`);
      process.exitCode = 1;
      return;
    }
    for (const step of FLOWS[slug]) {
      const md = /\*\*|\[.+?\]\(.+?\)|^#|^- /m;
      if (md.test(step.body) || md.test(step.title)) {
        console.error(`✗ ${slug} / ${step.title}: マークダウン記法が入っています`);
        broken = true;
      }
    }
  }
  if (broken) {
    console.error("\nプレーンテキストに直してから流し直してください。");
    process.exitCode = 1;
    return;
  }

  console.log(APPLY ? "== 投入 ==\n" : "== ドライラン(--apply で投入) ==\n");

  let total = 0;
  for (const slug of slugs) {
    const museum = await db.museum.findUnique({
      where: { slug },
      include: { visitFlow: true },
    });
    if (!museum) {
      console.error(`✗ ${slug}: 見つかりません`);
      process.exitCode = 1;
      continue;
    }

    const steps = FLOWS[slug];
    total += steps.length;
    const chars = steps.reduce((s, x) => s + x.body.length + x.title.length, 0);

    console.log(`${museum.name} (${slug})`);
    console.log(`  ${museum.visitFlow.length}→${steps.length}ステップ / ${chars}字`);
    steps.forEach((s) => console.log(`    ${s.kind.padEnd(9)} ${s.title}`));

    if (APPLY) {
      await db.$transaction([
        db.museumVisitStep.deleteMany({ where: { museumId: museum.id } }),
        db.museumVisitStep.createMany({
          data: steps.map((s, i) => ({
            museumId: museum.id,
            kind: s.kind,
            title: s.title,
            body: s.body,
            displayOrder: i + 1,
          })),
        }),
      ]);
      console.log("    → 投入");
    }
    console.log("");
  }

  console.log(`対象 ${slugs.length}館 / ${total}ステップ`);
  if (!APPLY) console.log("\n--apply を付けると投入します。");
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => db.$disconnect());
